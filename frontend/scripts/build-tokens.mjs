// Generates the global CSS from design/tokens.json, the single source of truth for the design system.
//   src/styles/tokens.css  CSS custom properties: colour (light + dark), spacing, radius, fonts, type scale
//   src/styles/theme.css   Tailwind @theme mapping so utilities (bg-panel, text-title, rounded-lg) use them
// Run `npm run tokens` after editing design/tokens.json. Both outputs are committed.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const tokens = JSON.parse(readFileSync(resolve(root, 'design/tokens.json'), 'utf8'))
const HEADER = '/* GENERATED by scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */\n'

const colors = tokens.color.tokens
const families = tokens.type.families
const styles = tokens.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: g.family })))
const lines = (list, indent = '  ') => list.map((l) => indent + l).join('\n')
const colorVars = (theme) => colors.map((c) => `--${c.name}: ${c.value[theme]};`)

// ---------- tokens.css ----------

const typeVars = styles.flatMap((s) => [
  `--type-${s.name}-size: ${s.fontSize};`,
  `--type-${s.name}-line: ${s.lineHeight};`,
  `--type-${s.name}-weight: ${s.fontWeight};`,
  `--type-${s.name}-tracking: ${s.letterSpacing ?? 'normal'};`,
  // Shorthand for `font:` in the token's default family.
  `--type-${s.name}: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${s.family});`,
])

const tokensCss = `${HEADER}
:root {
  color-scheme: light dark;

  /* Fonts */
${lines(Object.entries(families).map(([k, v]) => `--font-${k}: ${v};`))}

  /* Type scale */
${lines(typeVars)}

  /* Spacing */
${lines(tokens.spacing.tokens.map((t) => `--${t.name}: ${t.value};`))}

  /* Radius */
${lines(tokens.radius.tokens.map((t) => `--${t.name}: ${t.value};`))}

  /* Colour: light */
${lines(colorVars('light'))}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${lines(colorVars('dark'), '    ')}
  }
}

:root[data-theme="dark"] {
${lines(colorVars('dark'))}
}
`

// ---------- theme.css (Tailwind) ----------

const themeCss = `${HEADER}
/* Only design-system colours, radii and type sizes exist as utilities: Tailwind's defaults are cleared.
   Spacing keeps Tailwind's 4px scale, which already matches space-1 … space-8 (p-4 = 16px). */
@theme inline {
  --color-*: initial;
${lines(colors.map((c) => `--color-${c.name}: var(--${c.name});`))}

  /* Families only; --font-* is not cleared because that would also clear the --font-weight-* scale. */
${lines(Object.keys(families).map((k) => `--font-${k}: var(--font-${k});`))}

  --radius-*: initial;
${lines(tokens.radius.tokens.map((t) => `--${t.name}: var(--${t.name});`))}

  --text-*: initial;
${lines(
  styles.flatMap((s) => [
    `--text-${s.name}: var(--type-${s.name}-size);`,
    `--text-${s.name}--line-height: var(--type-${s.name}-line);`,
    `--text-${s.name}--font-weight: var(--type-${s.name}-weight);`,
    `--text-${s.name}--letter-spacing: var(--type-${s.name}-tracking);`,
  ]),
)}

  /* The design system has no shadows. */
  --shadow-*: initial;
  --inset-shadow-*: initial;
  --drop-shadow-*: initial;
}
`

writeFileSync(resolve(root, 'src/styles/tokens.css'), tokensCss)
writeFileSync(resolve(root, 'src/styles/theme.css'), themeCss)
console.log(`tokens: ${colors.length} colours, ${styles.length} type styles → src/styles/tokens.css, theme.css`)
